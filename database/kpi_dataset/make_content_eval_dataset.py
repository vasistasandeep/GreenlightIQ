"""Generate the committed KPI_Test_Dataset (the labeled truth sheet).

Builds ``content_eval_dataset.csv`` + ``content_eval_dataset.json`` and a sidecar
``DATASET_META.json`` for the Content_Eval_System (content-eval-model, task 8).
The dataset is the versioned, human-readable truth set every Content_Eval_Model
is measured against: a curated, well-stratified set of 50-100 titles spanning
tentpole / mid-budget genre / indie drama / international co-production / library
catalog, so the full Backtest_Harness and regression suite run offline in well
under the time budget (R3.1).

Each row carries a stable title id, the full Feature_Vector inputs the pure
:func:`app.domain.features.derive_features` consumes, the expected value for each
Modeled_Engagement_Driver (``projected_viewing_hours``, ``churn_reduction_pct``,
``watch_time_elasticity``, ``ad_load_receptivity``), the expected per-guardrail
outcome, the expected recommendation, a ``Label_Type`` (OBSERVED / PROXY /
SYNTHETIC -- here only PROXY and SYNTHETIC, labeled honestly), a ``release_year``,
a train/test ``split`` by the Temporal_Split cutoff, and a provenance note
(R3.2, R3.6).

Honesty posture (R2.6, R3.6): every row is a PROXY or SYNTHETIC label, never
OBSERVED -- no row in this dataset is a real, realized platform outcome. The five
seeded demo titles are backed by the open-data connector fixtures (PROXY); the
remaining coverage rows are deterministically SYNTHETIC and tagged as such. No
measurement over this dataset may present its accuracy as real-world accuracy.

Reproducibility (R2.5): the open-data correlates for the demo titles are read
from the committed, checksummed Source_Snapshots via the Connector_Registry
(``app.data.connectors.connector_registry.resolve_features``), so the generator
runs fully offline and deterministically. The SYNTHETIC rows are generated by a
fixed, seeded procedure (no wall-clock, no RNG state leakage), so re-running
yields byte-identical artifacts -- the basis for the idempotent ``--check`` mode.

Temporal_Split (R3.3, Property 11): rows are partitioned train/test by a recorded
release-year cutoff -- train on titles released on or before the cutoff, test on
titles released after it. NO random k-fold (which would leak future/franchise
signal). The cutoff is recorded in the dataset metadata block and the sidecar.

Usage::

    python database/kpi_dataset/make_content_eval_dataset.py            # write
    python database/kpi_dataset/make_content_eval_dataset.py --check     # verify

``--check`` is idempotent and writes nothing: it rebuilds the artifacts in memory
and exits non-zero if any committed file is missing or out of date, mirroring the
``sample-imports/make_*.py`` and ``database/seed/generate_seed_sql.py`` pattern.

Standard library only (csv, json, pathlib, argparse, hashlib). No third-party
dependency, no database, no network.
"""

