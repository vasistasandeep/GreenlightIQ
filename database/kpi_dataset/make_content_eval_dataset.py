def _artifacts() -> dict[Path, str]:
    """Build every committed artifact's path -> content mapping (in memory)."""
    rows = build_rows()
    metadata = build_metadata(rows)
    return {
        CSV_PATH: render_csv(rows),
        JSON_PATH: render_json(rows, metadata),
        META_PATH: render_meta(metadata),
    }


def write_artifacts() -> None:
    """Write every committed artifact to disk."""
    for path, content in _artifacts().items():
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text(content, encoding="utf-8")
        print(f"wrote {path}")


def check_artifacts() -> int:
    """Verify committed artifacts match a fresh in-memory build (no write).

    Returns 0 when every artifact is present and byte-identical to the freshly
    generated content, else 1 -- the idempotent, no-write ``--check`` contract
    (R3.1). Reports a concise per-file status.
    """
    ok = True
    for path, content in _artifacts().items():
        if not path.exists():
            print(f"MISSING {path} (run the generator to create it)")
            ok = False
            continue
        current = path.read_text(encoding="utf-8")
        if current == content:
            print(f"ok   {path.name} is up to date")
        else:
            cur_sum = hashlib.sha256(current.encode("utf-8")).hexdigest()[:12]
            new_sum = hashlib.sha256(content.encode("utf-8")).hexdigest()[:12]
            print(f"STALE {path.name} (committed {cur_sum} != expected {new_sum})")
            ok = False
    return 0 if ok else 1


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument(
        "--check",
        action="store_true",
        help="verify committed artifacts are up to date (idempotent, no write)",
    )
    args = parser.parse_args(argv)
    if args.check:
        return check_artifacts()
    write_artifacts()
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
