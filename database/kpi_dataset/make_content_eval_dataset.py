def _cycle(seq, i):
    """Deterministic pick from ``seq`` by index (pure, no RNG)."""
    return seq[i % len(seq)]


def _q2(value: float) -> str:
    """Quantize a float to 2 decimal places as a stable string."""
    return f"{value:.2f}"


def _recommendation_from_guardrails(guardrails: dict) -> str:
    """Derive the expected recommendation from the per-guardrail outcomes.

    Mirrors the engine's intent without importing it (the dataset is the
    independent truth): a non-correctable CHURN_MITIGATION breach is a hard PASS;
    any other breach downgrades a GREENLIGHT to NEGOTIATE_HARD; all-pass is a
    GREENLIGHT. This keeps the expected recommendation internally consistent with
    the expected per-guardrail outcomes the same row records (R3.2).
    """
    if not guardrails["CHURN_MITIGATION"]:
        return PASS
    breaches = [name for name in GUARDRAILS if not guardrails[name]]
    if not breaches:
        return GREENLIGHT
    return NEGOTIATE_HARD


def _synthetic_rows() -> list[dict]:
    """Build the deterministic SYNTHETIC coverage rows across all strata."""
    rows: list[dict] = []
    for stratum in STRATA:
        profile = STRATUM_PROFILES[stratum]
        for i in range(profile["count"]):
            rows.append(_synthetic_row(stratum, profile, i))
    return rows


def _synthetic_row(stratum: str, profile: dict, i: int) -> dict:
    """Build one SYNTHETIC row for ``stratum`` at block index ``i`` (pure)."""
    year = _cycle(profile["years"], i)
    # A deterministic quality dial in [0, 1] from the block index, used to vary
    # the open-data correlates and drivers smoothly across the block.
    span = max(profile["count"] - 1, 1)
    q = i / span  # 0.0 .. 1.0

    # Intrinsic numerics vary by stratum baseline + the quality dial.
    base_scale = {
        "tentpole": 8.0,
        "mid_budget_genre": 5.5,
        "indie_drama": 4.5,
        "international_coproduction": 6.0,
        "library_catalog": 3.0,
    }[stratum]
    base_pedigree = {
        "tentpole": 8.0,
        "mid_budget_genre": 6.0,
        "indie_drama": 5.5,
        "international_coproduction": 6.5,
        "library_catalog": 3.5,
    }[stratum]
    production_scale = _q2(min(10.0, base_scale + q * 1.5))
    talent_pedigree = _q2(min(10.0, base_pedigree + q * 1.5))
    runtime = {
        "tentpole": 140,
        "mid_budget_genre": 105,
        "indie_drama": 112,
        "international_coproduction": 95,
        "library_catalog": 88,
    }[stratum]
    is_exclusive = stratum in ("tentpole", "mid_budget_genre") or (i % 2 == 0)

    # Open-data correlates (PROXY-style numbers, but SYNTHETIC here). Varied by q
    # within a plausible per-stratum band; never a penalizing zero.
    normalized_rating = _q2(
        min(1.0, {
            "tentpole": 0.70,
            "mid_budget_genre": 0.60,
            "indie_drama": 0.68,
            "international_coproduction": 0.64,
            "library_catalog": 0.52,
        }[stratum] + q * 0.18)
    )
    log_vote_count = _q2(
        {
            "tentpole": 8.0,
            "mid_budget_genre": 5.5,
            "indie_drama": 4.0,
            "international_coproduction": 5.0,
            "library_catalog": 3.0,
        }[stratum] + q * 1.5
    )
    franchise_flag = bool(stratum == "tentpole" and i % 2 == 0)
    award_signal = _q2(
        min(1.0, {
            "tentpole": 0.45,
            "mid_budget_genre": 0.25,
            "indie_drama": 0.55,
            "international_coproduction": 0.40,
            "library_catalog": 0.12,
        }[stratum] + q * 0.25)
    )

    # Expected modeled drivers. Varied smoothly by stratum + quality dial so the
    # benchmark exercises the model across blockbusters and catalog titles.
    viewing_hours = {
        "tentpole": 160_000_000 + int(q * 140_000_000),
        "mid_budget_genre": 35_000_000 + int(q * 35_000_000),
        "indie_drama": 18_000_000 + int(q * 22_000_000),
        "international_coproduction": 60_000_000 + int(q * 60_000_000),
        "library_catalog": 45_000_000 + int(q * 35_000_000),
    }[stratum]
    churn_pct = {
        "tentpole": 1.90 + q * 0.50,
        "mid_budget_genre": 1.45 + q * 0.45,
        "indie_drama": 1.30 + q * 0.55,
        "international_coproduction": 1.60 + q * 0.45,
        "library_catalog": 0.70 + q * 0.75,
    }[stratum]
    watch_time_elasticity = {
        "tentpole": 1.05 + q * 0.20,
        "mid_budget_genre": 0.90 + q * 0.15,
        "indie_drama": 0.85 + q * 0.20,
        "international_coproduction": 0.95 + q * 0.15,
        "library_catalog": 0.75 + q * 0.15,
    }[stratum]
    ad_load_receptivity = {
        "tentpole": 1.02 + q * 0.06,
        "mid_budget_genre": 1.00 + q * 0.05,
        "indie_drama": 0.95 + q * 0.05,
        "international_coproduction": 0.98 + q * 0.05,
        "library_catalog": 1.08 + q * 0.07,
    }[stratum]

    # Expected per-guardrail outcomes, derived deterministically from the drivers
    # so each row's recommendation follows from its own expected values (R3.2).
    cpvh_ok = stratum != "mid_budget_genre" or q >= 0.5
    ltv_ok = not (stratum in ("indie_drama", "library_catalog") and q < 0.35)
    churn_ok = churn_pct >= 1.5
    payback_ok = not (stratum == "mid_budget_genre" and q < 0.35)
    guardrails = {
        "CPVH": bool(cpvh_ok),
        "LTV_TO_COST": bool(ltv_ok),
        "CHURN_MITIGATION": bool(churn_ok),
        "PAYBACK_HORIZON": bool(payback_ok),
    }
    recommendation = _recommendation_from_guardrails(guardrails)

    title_id = f"syn-{stratum}-{i:02d}"
    return {
        "title_id": title_id,
        "title_name": f"{stratum.replace('_', ' ').title()} Synthetic {i:02d}",
        "stratum": stratum,
        "label_type": LABEL_SYNTHETIC,
        "release_year": year,
        "features": {
            "asset_type": profile["asset_type"],
            "genre": profile["genre"],
            "content_format": profile["content_format"],
            "runtime_minutes": runtime,
            "is_exclusive": bool(is_exclusive),
            "production_scale": production_scale,
            "talent_pedigree": talent_pedigree,
            "normalized_rating": normalized_rating,
            "log_vote_count": log_vote_count,
            "franchise_flag": franchise_flag,
            "award_signal": award_signal,
        },
        "expected_drivers": {
            "projected_viewing_hours": str(viewing_hours),
            "churn_reduction_pct": _q2(churn_pct),
            "watch_time_elasticity": _q2(watch_time_elasticity),
            "ad_load_receptivity": _q2(ad_load_receptivity),
        },
        "expected_guardrails": guardrails,
        "expected_recommendation": recommendation,
        "provenance": "Synthetic coverage row (generated for stratification; no real outcome).",
    }


def _demo_rows() -> list[dict]:
    """Build the five pinned demo rows (PROXY), reading correlates from snapshots.

    The open-data correlates (normalized_rating, log_vote_count, franchise_flag,
    award_signal, runtime_minutes, release_year) are resolved from the committed,
    checksummed Source_Snapshots through the Connector_Registry, so the demo rows
    are reproducible and offline (R2.5, R9.2). The intrinsic fields and expected
    drivers/verdicts are pinned to the current seeded demo (R3.4).
    """
    resolved = resolve_features()  # snapshot-only, checksum-verified (R9.4)
    raw_by_title = resolved_to_raw(resolved)

    rows: list[dict] = []
    for demo in DEMO_TITLES:
        correlates = raw_by_title.get(demo["connector_id"], {})
        intrinsic = demo["intrinsic"]

        # release_year and runtime come from the connector snapshot (IMDb); the
        # correlates come from TMDB / Wikidata via the registry's precedence.
        release_year = correlates.get("release_year")
        runtime_minutes = correlates.get("runtime_minutes")
        features = {
            "asset_type": intrinsic["asset_type"],
            "genre": intrinsic["genre"],
            "content_format": intrinsic["content_format"],
            "runtime_minutes": runtime_minutes,
            "is_exclusive": intrinsic["is_exclusive"],
            "production_scale": intrinsic["production_scale"],
            "talent_pedigree": intrinsic["talent_pedigree"],
            "normalized_rating": _opt(correlates.get("normalized_rating")),
            "log_vote_count": _opt(correlates.get("log_vote_count")),
            "franchise_flag": bool(correlates.get("franchise_flag", False)),
            "award_signal": _opt(correlates.get("award_signal")),
        }
        rows.append(
            {
                "title_id": demo["title_id"],
                "title_name": demo["title_name"],
                "stratum": demo["stratum"],
                "label_type": LABEL_PROXY,
                "release_year": int(release_year) if release_year is not None else None,
                "features": features,
                "expected_drivers": dict(demo["drivers"]),
                "expected_guardrails": dict(demo["guardrails"]),
                "expected_recommendation": demo["recommendation"],
                "provenance": (
                    "Seeded demo title; open-data correlates from committed "
                    f"Source_Snapshots (connector id {demo['connector_id']}); "
                    "expected verdict pinned to the seeded demo."
                ),
            }
        )
    return rows


def _opt(value):
    """Pass a correlate value through unchanged (kept explicit for readability)."""
    return value


