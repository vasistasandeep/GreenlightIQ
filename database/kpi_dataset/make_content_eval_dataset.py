def build_rows() -> list[dict]:
    """Build every dataset row (demo PROXY rows first, then SYNTHETIC coverage).

    Applies the Temporal_Split: a row is ``train`` when its release_year is on or
    before :data:`TEMPORAL_CUTOFF_YEAR`, else ``test`` (R3.3, Property 11). A row
    with no release year is conservatively assigned to the training split (it can
    never leak into a held-out metric).
    """
    rows = _demo_rows() + _synthetic_rows()
    for row in rows:
        year = row.get("release_year")
        if year is None:
            row["split"] = "train"
        else:
            row["split"] = "train" if int(year) <= TEMPORAL_CUTOFF_YEAR else "test"
    return rows


def build_metadata(rows: list[dict]) -> dict:
    """Build the dataset-level metadata block (R3.5)."""
    label_counts: dict[str, int] = {}
    stratum_counts: dict[str, int] = {}
    split_counts: dict[str, int] = {}
    for row in rows:
        label_counts[row["label_type"]] = label_counts.get(row["label_type"], 0) + 1
        stratum_counts[row["stratum"]] = stratum_counts.get(row["stratum"], 0) + 1
        split_counts[row["split"]] = split_counts.get(row["split"], 0) + 1
    return {
        "version": DATASET_VERSION,
        "created": DATASET_DATE,
        "temporal_cutoff_year": TEMPORAL_CUTOFF_YEAR,
        "split_rule": (
            "train = release_year <= cutoff; test = release_year > cutoff "
            "(Temporal_Split, no random k-fold)"
        ),
        "dominant_label_type": DOMINANT_LABEL_TYPE,
        "row_count": len(rows),
        "label_type_counts": dict(sorted(label_counts.items())),
        "stratum_counts": dict(sorted(stratum_counts.items())),
        "split_counts": dict(sorted(split_counts.items())),
        "strata": list(STRATA),
        "feature_keys": list(FEATURE_KEYS),
        "driver_keys": list(DRIVER_KEYS),
        "guardrails": list(GUARDRAILS),
        "sources": _source_manifest(),
        "honesty_note": (
            "Every row is PROXY or SYNTHETIC -- no OBSERVED (real realized) "
            "outcomes. Any measurement over this dataset is proxy accuracy, not "
            "real-world accuracy."
        ),
    }


# The flat CSV column order. Nested feature/driver/guardrail fields are flattened
# with documented prefixes so the CSV is human-readable and round-trips 1:1 with
# the JSON rows.
CSV_COLUMNS = (
    ["title_id", "title_name", "stratum", "label_type", "release_year", "split"]
    + [f"feat_{k}" for k in FEATURE_KEYS]
    + [f"exp_{k}" for k in DRIVER_KEYS]
    + [f"guardrail_{g}" for g in GUARDRAILS]
    + ["expected_recommendation", "provenance"]
)


def _csv_cell(value) -> str:
    """Render a Python value as a stable CSV cell string."""
    if value is None:
        return ""
    if isinstance(value, bool):
        return "true" if value else "false"
    return str(value)


def render_csv(rows: list[dict]) -> str:
    """Render the dataset rows to a deterministic CSV string."""
    buffer = io.StringIO()
    writer = csv.writer(buffer, lineterminator="\n")
    writer.writerow(CSV_COLUMNS)
    for row in rows:
        feats = row["features"]
        drivers = row["expected_drivers"]
        guardrails = row["expected_guardrails"]
        line = [
            row["title_id"],
            row["title_name"],
            row["stratum"],
            row["label_type"],
            _csv_cell(row["release_year"]),
            row["split"],
        ]
        line += [_csv_cell(feats.get(k)) for k in FEATURE_KEYS]
        line += [_csv_cell(drivers.get(k)) for k in DRIVER_KEYS]
        line += [_csv_cell(guardrails.get(g)) for g in GUARDRAILS]
        line += [row["expected_recommendation"], row["provenance"]]
        writer.writerow(line)
    return buffer.getvalue()


def render_json(rows: list[dict], metadata: dict) -> str:
    """Render the dataset to a deterministic, pretty JSON string."""
    payload = {"metadata": metadata, "rows": rows}
    return json.dumps(payload, indent=2, sort_keys=True) + "\n"


def render_meta(metadata: dict) -> str:
    """Render the sidecar DATASET_META.json string."""
    return json.dumps(metadata, indent=2, sort_keys=True) + "\n"


